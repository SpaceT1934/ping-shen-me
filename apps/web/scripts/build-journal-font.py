"""Build locally hosted, complete, demand-loaded JournalHand font subsets.

Requires fonttools[woff] and the official MaShanZheng-Regular.ttf (OFL).
Usage: python apps/web/scripts/build-journal-font.py /path/to/MaShanZheng-Regular.ttf
The source font and build dependencies are not needed by the running app or CI.
"""

import argparse
import hashlib
import json
import re
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont


def unicode_ranges(points):
    runs = []
    for point in sorted(points):
        if runs and point == runs[-1][1] + 1:
            runs[-1][1] = point
        else:
            runs.append([point, point])
    return ", ".join(
        f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}"
        for start, end in runs
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[3]
    destination = root / "apps/web/public/assets/journal/fonts"
    destination.mkdir(exist_ok=True)
    available = set(TTFont(args.source).getBestCmap())
    core = set(range(32, 127))
    # Include backend/domain copy as well as frontend strings, unlike the old subset.
    for base in (
        "apps/web/src", "apps/api/src", "apps/ai/ai_service",
        "packages/contracts/src", "packages/domain/src",
    ):
        for path in (root / base).rglob("*"):
            if path.suffix in {".ts", ".tsx", ".py"}:
                core.update(map(ord, path.read_text()))
    grouping = json.loads(Path(__file__).with_name("journal-font-groups.json").read_text())
    # These final Google Fonts groups contain common text/punctuation.
    for group in grouping["groups"][-2:]:
        core.update(map(ord, group))
    core &= available
    covered = set(core)
    groups = [("core", core)]
    pending = set()
    for group in reversed(grouping["groups"]):
        points = set(map(ord, group)) - covered
        pending.update(points)
        covered.update(points)
        if len(pending) >= 96:
            groups.append((f"extra-{len(groups):02}", pending))
            pending = set()
    pending.update(available - covered)
    if pending:
        groups.append((f"extra-{len(groups):02}", pending))

    faces = []
    outputs = []
    seen = set()
    for name, points in groups:
        assert not (seen & points), "Overlapping font faces"
        seen.update(points)
        options = subset.Options()
        options.flavor = "woff2"
        options.desubroutinize = True
        font = subset.load_font(str(args.source), options)
        builder = subset.Subsetter(options=options)
        builder.populate(unicodes=points)
        builder.subset(font)
        # Shared glyph aliases can otherwise survive subsetting in another face.
        for table in font["cmap"].tables:
            if table.isUnicode() and hasattr(table, "cmap"):
                table.cmap = {point: glyph for point, glyph in table.cmap.items() if point in points}
        temporary = destination / f"{name}.woff2"
        subset.save_font(font, str(temporary), options)
        # Coverage is validated against the real output, not just the requested set.
        actual = set(TTFont(temporary).getBestCmap())
        assert actual == points, f"{name}: missing {points-actual}; unexpected {actual-points}"
        digest = hashlib.sha256(temporary.read_bytes()).hexdigest()[:12]
        output = destination / f"{name}-{digest}.woff2"
        temporary.replace(output)
        outputs.append(output)
        faces.append(
            "@font-face {\n"
            "  font-family: JournalHand;\n"
            "  font-style: normal;\n"
            "  font-weight: 400;\n"
            "  font-display: swap;\n"
            f"  src: url('/assets/journal/fonts/{output.name}') format('woff2');\n"
            f"  unicode-range: {unicode_ranges(points)};\n"
            "}"
        )
    assert seen == available, "Original font glyphs must all be covered"
    for stale in destination.glob("*.woff2"):
        if stale not in outputs:
            stale.unlink()
    (root / "apps/web/src/styles/journal-fonts.css").write_text(
        "/* Generated by apps/web/scripts/build-journal-font.py; do not edit by hand. */\n"
        + "\n".join(faces) + "\n"
    )
    html_path = root / "apps/web/index.html"
    preload = (
        "<!-- journal-font-preload -->\n"
        f'    <link rel="preload" href="/assets/journal/fonts/{outputs[0].name}" '
        'as="font" type="font/woff2" crossorigin />\n'
        "    <!-- /journal-font-preload -->"
    )
    html = html_path.read_text()
    if "<!-- journal-font-preload -->" in html:
        html = re.sub(r"<!-- journal-font-preload -->.*?<!-- /journal-font-preload -->", preload, html, flags=re.S)
    else:
        html = html.replace("    <title>", f"    {preload}\n    <title>")
    html_path.write_text(html)
    print(f"Covered all {len(seen)} source glyphs in {len(groups)} non-overlapping faces.")
    print(f"Core: {len(core)} glyphs, {outputs[0].stat().st_size} bytes; extras load only when used.")


if __name__ == "__main__":
    main()
